/**
 * Sync experiments/personal-coach/coach-policy-rules.md → api/coach-policy.js
 * Run after editing policy rules: node scripts/sync-coach-policy.js
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const src = path.join(root, "experiments", "personal-coach", "coach-policy-rules.md");
const dest = path.join(root, "api", "coach-policy.js");

if (!fs.existsSync(src)) {
  console.error("Missing", src);
  process.exit(1);
}

const md = fs.readFileSync(src, "utf8");
/* Prefer Active rules section for the injected prompt (keeps tokens down). */
let body = md;
const activeIdx = md.search(/^## Active rules\s*$/m);
if (activeIdx >= 0) {
  const fromActive = md.slice(activeIdx);
  const notesIdx = fromActive.search(/^## Notes for maintainers\s*$/m);
  body = notesIdx >= 0 ? fromActive.slice(0, notesIdx).trim() : fromActive.trim();
}

const normalized = body.replace(/\r\n/g, "\n").trim();
const header =
  "COACH POLICY RULES (HARD/SOFT — obey HARD; prefer SOFT when no conflict):\n" +
  "Drive/File Search = knowledge. This block = required behavior.\n\n";

fs.writeFileSync(
  dest,
  "/** Auto-generated by scripts/sync-coach-policy.js — do not edit by hand. */\n" +
    "module.exports = " +
    JSON.stringify(header + normalized) +
    ";\n"
);
console.log("synced coach-policy.js", (header + normalized).length, "chars");
