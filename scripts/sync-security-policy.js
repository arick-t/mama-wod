/**
 * Sync experiments/security-coach/security-policy-rules.md → lib/security-policy.js
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const src = path.join(root, "experiments", "security-coach", "security-policy-rules.md");
const dest = path.join(root, "lib", "security-policy.js");

if (!fs.existsSync(src)) {
  console.error("Missing", src);
  process.exit(1);
}

const md = fs.readFileSync(src, "utf8");
let body = md;
const activeIdx = md.search(/^## Active rules\s*$/m);
if (activeIdx >= 0) {
  body = md.slice(activeIdx).trim();
}

const normalized = body.replace(/\r\n/g, "\n").trim();
const header =
  "SECURITY COACH POLICY RULES (HARD/SOFT — obey HARD; prefer SOFT when no conflict):\n" +
  "Project context = evidence. This block = mandatory behavior.\n\n";

fs.writeFileSync(
  dest,
  "/** Auto-generated by scripts/sync-security-policy.js — do not edit by hand. */\n" +
    "module.exports = " +
    JSON.stringify(header + normalized) +
    ";\n"
);

console.log("synced security-policy.js", (header + normalized).length, "chars");
